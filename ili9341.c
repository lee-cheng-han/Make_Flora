  LCD_WriteCmd(0xCF);
  LCD_WriteData8(0x00); LCD_WriteData8(0xC1); LCD_WriteData8(0x30);
  LCD_WriteCmd(0xE8);
  LCD_WriteData8(0x85); LCD_WriteData8(0x00); LCD_WriteData8(0x78);
  LCD_WriteCmd(0xEA);
  LCD_WriteData8(0x00); LCD_WriteData8(0x00);
  LCD_WriteCmd(0xED);
  LCD_WriteData8(0x64); LCD_WriteData8(0x03);
  LCD_WriteData8(0x12); LCD_WriteData8(0x81);
  LCD_WriteCmd(0xF7); LCD_WriteData8(0x20);
  LCD_WriteCmd(0xC0); LCD_WriteData8(0x23);
  LCD_WriteCmd(0xC1); LCD_WriteData8(0x10);
  LCD_WriteCmd(0xC5); LCD_WriteData8(0x3E); LCD_WriteData8(0x28);
  LCD_WriteCmd(0xC7); LCD_WriteData8(0x86);

  /* Set rotation explicitly via SetRotation() later */
  
  LCD_WriteCmd(0x3A); LCD_WriteData8(0x55);
